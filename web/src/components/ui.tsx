/** Minimal formatting for AI/WhatsApp text: **bold** / *bold*, _italic_, "- " bullets, newlines. */
export function RichText({ text, className = '' }: { text: string; className?: string }) {
  const lines = text.split('\n')
  const out: ReactNode[] = []
  let bullets: ReactNode[] = []
  const flush = () => {
    if (bullets.length) out.push(<ul key={`ul${out.length}`} className="my-1 list-disc space-y-0.5 pl-5">{bullets}</ul>)
    bullets = []
  }
  lines.forEach((line, i) => {
    const m = line.match(/^\s*(?:[-•*]|\d+\.)\s+(.*)$/)
    if (m && !/^\*[^*]+\*/.test(line.trim())) {
      bullets.push(<li key={i}>{inline(m[1])}</li>)
    } else {
      flush()
      if (line.trim()) out.push(<p key={i} className="my-1">{inline(line)}</p>)
    }
  })
  flush()
  return <div className={className}>{out}</div>
}

function inline(s: string): ReactNode[] {
  const parts = s.split(/(\*\*[^*]+\*\*|\*[^*\s][^*]*\*|_[^_\s][^_]*_)/g)
  return parts.map((p, i) => {
    if (/^\*\*.+\*\*$/.test(p)) return <strong key={i}>{p.slice(2, -2)}</strong>
    if (/^\*.+\*$/.test(p)) return <strong key={i}>{p.slice(1, -1)}</strong>
    if (/^_.+_$/.test(p)) return <em key={i} className="text-slate-500">{p.slice(1, -1)}</em>
    return p
  })
}

